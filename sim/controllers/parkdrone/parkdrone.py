"""
PARKDRONE Webots controller — autonomous street patrol + camera capture.

Flight stabilisation is adapted from Webots' official Mavic 2 PRO sample
(propeller-mixing PD on roll/pitch/altitude). On top of it we add a simple
waypoint navigator that turns toward the next waypoint then flies forward,
following the street bay-rows (worlds/route.json, built by generate_world.py;
falls back to a square lawnmower if absent) and saving a camera frame (plus
drone pose, for later georeferencing) at each waypoint.

UNTESTED outside Webots — device names assume the Mavic2Pro proto. Open
worlds/fmi_block.wbt in Webots to run; tune the constants there.
"""
