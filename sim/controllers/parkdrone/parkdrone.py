def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def wrap(a):
    return (a + math.pi) % (2 * math.pi) - math.pi


def lawnmower(half, step):
    wps, y, going_right = [], -half, True
    while y <= half:
        xs = [-half, half] if going_right else [half, -half]
        for x in xs:
            wps.append((x, y))
        y += step
        going_right = not going_right
    return wps


def load_route():
    """Waypoints that follow the streets, generated by generate_world.py (in
    the same local metres as the world). The world passes its own route file
    via controllerArgs (e.g. fmi_block_1km.route.json) so several survey areas
    can coexist in worlds/; default is the legacy route.json. Fall back to a blind
    square lawnmower if the file is missing."""
    path = os.path.join(WORLDS, ROUTE_FILE)
    try:
        wps = [tuple(p) for p in json.load(open(path, encoding="utf-8"))]
        if wps:
            print(f"[parkdrone] loaded {len(wps)} route waypoints from {path}")
            return wps
        print(f"[parkdrone] !! {path} is empty -> falling back to lawnmower")
    except (OSError, ValueError) as e:
        print(f"[parkdrone] !! no usable {ROUTE_FILE} ({e}) -> lawnmower fallback")
    return lawnmower(HALF, LANE_STEP)


