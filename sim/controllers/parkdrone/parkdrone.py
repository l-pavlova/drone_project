TARGET_ALT = 30.0          # metres
# --- landing (end of patrol) ----------------------------------------------
# The patrol used to end by damping horizontal drift and nothing else, which
# leaves the drone hovering at 30 m indefinitely - and SPINNING, because
# yaw_d was reset to 0 every step and never given a damping term. Zero yaw
# command is not zero yaw RATE: there is no aerodynamic drag in the sim, so
# whatever rotation the last waypoint left it with simply persists. The drone
# was still turning on the spot minutes after finishing.
LAND_RATE = 1.0            # m/s descent while high
LAND_SLOW_ALT = 6.0        # m: below this, come down gently for the touchdown
LAND_RATE_SLOW = 0.35      # m/s
LAND_CUT_ALT = 0.30        # m: cut the motors here rather than driving them
#   into the ground - the last 30 cm is a settle, and holding thrust against
#   the floor makes the airframe skate.
WP_REACH = 6.0             # arrival basin (m); must stay generous or the drone
#   orbits waypoints it can't converge into. The frame is NOT taken on entering
#   the basin but at closest approach, so captures stay tight to the route:
#   arrive when really close (WP_CAPTURE), when receding 1 m past the closest
#   pass, or after WP_TIMEOUT near the waypoint. The timeout matters: at cruise
#   speed the turn radius is ~4 m, so the drone can settle into a stable ORBIT
#   inside the basin with constant distance - no distance-based test ever fires.
WP_CAPTURE = 2.5           # capture immediately once this close to the waypoint
WP_TIMEOUT = 8.0           # s near the waypoint before capturing anyway (orbit)
AIM_BLEND = 15.0           # m: within this range of the current waypoint the
#   nose aims progressively at the NEXT one (carrot / pure-pursuit style), so
#   straight legs flow through the 10 m waypoints without a stop-and-turn at
#   each hand-off (the drone visibly "danced" its yaw every waypoint without
#   this). Arrival/capture still keys off the CURRENT waypoint distance, and
#   at route reversals the blended aim swings behind -> yaw gate brakes the
#   drone and it U-turns on the spot, same as before.
LANE_STEP = 25.0           # spacing between lawnmower lanes (fallback only)
HALF = 65.0                # window half-size to cover (fallback only)


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def wrap(a):
    return (a + math.pi) % (2 * math.pi) - math.pi


def lawnmower(half, step):
    wps, y, going_right = [], -half, True
    while y <= half:
        xs = [-half, half] if going_right else [half, -half]
        for x in xs:
            wps.append((x, y))
        y += step
        going_right = not going_right
    return wps


def load_route():
    """Waypoints that follow the streets, generated by generate_world.py (in
    the same local metres as the world). The world passes its own route file
    via controllerArgs (e.g. fmi_block_1km.route.json) so several survey areas
    can coexist in worlds/; default is the legacy route.json. Fall back to a blind
    square lawnmower if the file is missing."""
    path = os.path.join(WORLDS, ROUTE_FILE)
    try:
        wps = [tuple(p) for p in json.load(open(path, encoding="utf-8"))]
        if wps:
            print(f"[parkdrone] loaded {len(wps)} route waypoints from {path}")
            return wps
        print(f"[parkdrone] !! {path} is empty -> falling back to lawnmower")
    except (OSError, ValueError) as e:
        print(f"[parkdrone] !! no usable {ROUTE_FILE} ({e}) -> lawnmower fallback")
    return lawnmower(HALF, LANE_STEP)


